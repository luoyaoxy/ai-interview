"""Application errors exposed through the HTTP boundary."""

from typing import Any


class ServiceError(Exception):
    """Structured error that can be safely converted to an API response."""

    def __init__(
        self,
        *,
        status_code: int,
        code: str,
        message: str,
        details: dict[str, Any] | None = None,
    ) -> None:
        super().__init__(message)
        self.status_code = status_code
        self.code = code
        self.message = message
        self.details = details or {}
